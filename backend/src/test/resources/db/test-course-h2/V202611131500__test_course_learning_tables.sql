CREATE TABLE lesson_prerequisites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id BIGINT NOT NULL,
    prerequisite_lesson_id BIGINT,
    prerequisite_exam_id BIGINT,
    condition_type VARCHAR(30) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_lesson_prerequisites_lesson UNIQUE (lesson_id),
    CONSTRAINT chk_lesson_prerequisites_target CHECK (
        (condition_type = 'COMPLETE_LESSON'
            AND prerequisite_lesson_id IS NOT NULL
            AND prerequisite_exam_id IS NULL)
        OR
        (condition_type = 'PASS_EXAM'
            AND prerequisite_lesson_id IS NULL
            AND prerequisite_exam_id IS NOT NULL)
    ),
    CONSTRAINT chk_lesson_prerequisites_not_self CHECK (
        prerequisite_lesson_id IS NULL OR lesson_id <> prerequisite_lesson_id
    ),
    CONSTRAINT fk_lesson_prerequisites_lesson FOREIGN KEY (lesson_id)
        REFERENCES lessons (id) ON DELETE CASCADE,
    CONSTRAINT fk_lesson_prerequisites_prerequisite_lesson FOREIGN KEY (prerequisite_lesson_id)
        REFERENCES lessons (id) ON DELETE CASCADE,
    CONSTRAINT fk_lesson_prerequisites_prerequisite_exam FOREIGN KEY (prerequisite_exam_id)
        REFERENCES exams (id) ON DELETE CASCADE
);

CREATE INDEX idx_lesson_prerequisites_lesson_target
    ON lesson_prerequisites (prerequisite_lesson_id);
CREATE INDEX idx_lesson_prerequisites_exam_target
    ON lesson_prerequisites (prerequisite_exam_id);

CREATE TABLE lesson_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    course_id BIGINT NOT NULL,
    lesson_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'NOT_STARTED',
    watched_seconds INTEGER NOT NULL DEFAULT 0,
    progress_percent DECIMAL(5,2) NOT NULL DEFAULT 0,
    completion_source VARCHAR(30),
    first_accessed_at TIMESTAMP,
    last_accessed_at TIMESTAMP,
    completed_at TIMESTAMP,
    last_heartbeat_event_id VARCHAR(64),
    last_completion_event_id VARCHAR(64),
    overridden_by BIGINT,
    override_reason VARCHAR(500),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_lesson_progress_student_course_lesson UNIQUE (student_id, course_id, lesson_id),
    CONSTRAINT fk_lesson_progress_student FOREIGN KEY (student_id) REFERENCES users (id),
    CONSTRAINT fk_lesson_progress_course FOREIGN KEY (course_id) REFERENCES courses (id),
    CONSTRAINT fk_lesson_progress_lesson FOREIGN KEY (lesson_id) REFERENCES lessons (id),
    CONSTRAINT fk_lesson_progress_overridden_by FOREIGN KEY (overridden_by) REFERENCES users (id)
);

CREATE INDEX idx_lesson_progress_student_course_status
    ON lesson_progress (student_id, course_id, status);
CREATE INDEX idx_lesson_progress_student_accessed
    ON lesson_progress (student_id, last_accessed_at);

CREATE TABLE course_completions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    course_id BIGINT NOT NULL,
    completion_rule VARCHAR(60) NOT NULL,
    progress_percent_snapshot DECIMAL(5,2) NOT NULL,
    mandatory_lessons_snapshot INTEGER NOT NULL,
    completed_lessons_snapshot INTEGER NOT NULL,
    completed_at TIMESTAMP NOT NULL,
    created_by BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_course_completions_student_course UNIQUE (student_id, course_id),
    CONSTRAINT fk_course_completions_student FOREIGN KEY (student_id) REFERENCES users (id),
    CONSTRAINT fk_course_completions_course FOREIGN KEY (course_id) REFERENCES courses (id),
    CONSTRAINT fk_course_completions_created_by FOREIGN KEY (created_by) REFERENCES users (id)
);

CREATE INDEX idx_course_completions_course_completed
    ON course_completions (course_id, completed_at);

CREATE TABLE lesson_resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id BIGINT NOT NULL,
    file_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    resource_type VARCHAR(20) NOT NULL,
    downloadable BOOLEAN NOT NULL DEFAULT TRUE,
    position INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_lesson_resources_lesson_file UNIQUE (lesson_id, file_id),
    CONSTRAINT uk_lesson_resources_lesson_position UNIQUE (lesson_id, position),
    CONSTRAINT fk_lesson_resources_lesson FOREIGN KEY (lesson_id)
        REFERENCES lessons (id) ON DELETE CASCADE,
    CONSTRAINT fk_lesson_resources_file FOREIGN KEY (file_id)
        REFERENCES file_resources (id)
);
